// Explicit browser smoke check; run with: node scripts/browser-check.mjs
import { chromium } from '@playwright/test';
import { createApp } from '../server/app.js';
import { mkdtempSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import {diagnosticFixture} from './diagnostic-fixture.mjs';

const directory = mkdtempSync(join(tmpdir(),'bmsport-browser-'));
const { app,store } = createApp(join(directory,'browser.sqlite'));
const server = app.listen(0,'127.0.0.1');
await new Promise(resolve => server.once('listening',resolve));
let browser;
try {
  browser = await chromium.launch({ channel:'msedge', headless:true });
  console.log('Browser launched');
  const page = await browser.newPage();
  page.setDefaultTimeout(15000);
  const errors=[]; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  console.log('App loaded');
  const model = page.getByRole('combobox',{name:'Модель автомобиля'});
  assert.equal(await model.isVisible(),false);
  const brand = page.getByRole('combobox',{name:'Марка автомобиля'});
  await brand.click();
  const allBrands = await page.locator('[role=listbox]:visible [role=option]').count();
  assert.ok(allBrands > 100);
  await brand.fill('M');
  const filteredBrands = await page.locator('[role=listbox]:visible [role=option]').count();
  assert.ok(filteredBrands > 1 && filteredBrands < allBrands);
  await brand.fill('Mer');
  assert.equal(await page.locator('[role=listbox]:visible [role=option]').count(),1);
  await page.getByRole('option',{name:'Mercedes-Benz',exact:true}).click();
  assert.equal(await brand.inputValue(),'Mercedes-Benz');
  await brand.fill('бм');
  await brand.press('ArrowDown'); await brand.press('Enter');
  assert.equal(await brand.inputValue(),'BMW');
  await model.click();
  const allModels = await page.locator('[role=listbox]:visible [role=option]').count(); assert.ok(allModels > 20);
  assert.equal(await page.getByRole('option',{name:'2002',exact:true}).count(),0);
  await model.fill('3');
  await page.getByRole('option',{name:'3 серия',exact:true}).click();
  assert.equal(await model.getAttribute('aria-expanded'),'true');
  assert.equal(await page.locator('[role=listbox]:visible [role=option]').count(),17);
  await model.fill('E'); assert.ok(await page.locator('[role=listbox]:visible [role=option]').count() > 1);
  await model.fill('E46'); assert.equal(await page.locator('[role=listbox]:visible [role=option]').count(),2);
  await page.getByRole('option',{name:'3 серия · E46',exact:true}).click();
  assert.equal(await model.inputValue(),'3 серия · E46');
  assert.equal(await page.getByLabel('Автомобиль *',{exact:true}).inputValue(),'BMW 3 серия · E46');
  await model.click(); await page.getByRole('button',{name:'← Все модели · 3 серия',exact:true}).click();
  assert.equal(await page.getByRole('option',{name:'5 серия',exact:true}).count(),1);
  await model.fill('X'); const xModels = await page.locator('[role=listbox]:visible [role=option]').count(); assert.ok(xModels > 1 && xModels < allModels);
  await model.fill('X5'); assert.equal(await page.locator('[role=listbox]:visible [role=option]').count(),2);
  await page.getByRole('option',{name:'X5',exact:true}).click();
  assert.equal(await page.getByLabel('Автомобиль *',{exact:true}).inputValue(),'BMW X5');
  await brand.fill('Toyota'); await brand.press('ArrowDown'); await brand.press('Enter');
  assert.equal(await model.inputValue(),'');
  await model.click(); assert.equal(await page.getByRole('option',{name:'X5',exact:true}).count(),0);
  await model.fill('Cam'); await page.getByRole('option',{name:'Camry',exact:true}).click();
  await brand.fill('BMW'); await brand.press('ArrowDown'); await brand.press('Enter');
  await model.fill('X5'); await page.getByRole('option',{name:'X5',exact:true}).click();
  await model.fill('3'); await model.press('ArrowDown'); await model.press('Enter');
  await model.fill('E46'); await model.press('ArrowDown'); await model.press('Enter');
  assert.equal(await model.inputValue(),'3 серия · E46');
  await page.getByLabel('Клиент *',{exact:true}).fill('Тестовый клиент');
  await page.getByLabel('Автомобиль *',{exact:true}).fill('BMW 530i');
  await page.getByRole('tab',{name:/Диагностика/}).click();
  await page.getByRole('button',{name:'+ Добавить ошибку',exact:true}).click();
  await page.getByLabel('Код',{exact:true}).fill('118001');
  await page.getByLabel('Описание *',{exact:true}).fill('Ошибка смеси');
  await page.getByRole('combobox',{name:'Статус',exact:true}).selectOption('fixed');
  await page.getByLabel('Выполненные работы',{exact:true}).fill('Устранён подсос воздуха');
  await page.getByRole('tab',{name:'Документы',exact:true}).click();
  const diagnosticBytes=await diagnosticFixture();
  await page.getByLabel('Прикрепить PDF диагностики',{exact:true}).setInputFiles({name:'diagnostic.pdf',mimeType:'application/pdf',buffer:diagnosticBytes});
  await page.getByRole('status').filter({hasText:'PDF распознан'}).waitFor();
  assert.equal(await page.locator('.diagnostic-table tbody tr').count(),5);
  const diagnosticEditor=page.getByLabel('Проверить и исправить распознанный текст',{exact:true});
  await page.getByText('Исходный текст PDF — для проверки и исправлений',{exact:true}).click();
  const originalDiagnosticText=await diagnosticEditor.inputValue();
  await diagnosticEditor.fill(originalDiagnosticText.replace('118001','118002'));
  await page.getByRole('button',{name:'Обновить коды по тексту',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Коды обновлены'}).waitFor();
  assert.equal(await page.locator('.diagnostic-table').getByText('118002',{exact:true}).count(),1);
  await page.getByRole('button',{name:'Добавить найденные коды в ошибки',exact:true}).click();
  assert.equal(await page.locator('#issues fieldset').count(),6);
  await page.getByRole('tab',{name:'Документы',exact:true}).click();
  await page.getByRole('button',{name:'Добавить найденные коды в ошибки',exact:true}).click();
  assert.equal(await page.locator('#issues fieldset').count(),6);
  await page.getByRole('button',{name:'Сохранить посещение',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Посещение сохранено'}).waitFor();
  // Simulate a visit saved before the English, same-line-only format was introduced.
  const legacy=store.list()[0];delete legacy.diagnosticPdf.analysis.formatVersion;store.save(legacy);
  await page.reload();
  await page.getByRole('button',{name:/BMW 530i/}).click();
  await page.getByRole('status').filter({hasText:'Описания переведены на английский'}).waitFor();
  await page.getByRole('tab',{name:/Диагностика/}).click();
  assert.match(await page.getByLabel('Описание *',{exact:true}).first().inputValue(),/mixture|mix/i);
  assert.equal(await page.getByRole('combobox',{name:'Статус',exact:true}).first().inputValue(),'fixed');
  assert.equal(await page.locator('.diagnostic-table tbody tr').count(),5);
  assert.ok((await diagnosticEditor.inputValue()).includes('118002'));
  assert.equal(await brand.inputValue(),'BMW');
  assert.equal(await model.inputValue(),'3 серия · E46');
  const attachmentLink = page.getByRole('link',{name:'Открыть PDF диагностики'});
  await page.getByRole('tab',{name:'Документы',exact:true}).click();
  await attachmentLink.waitFor();
  const attachmentResponse = await page.request.get(new URL(await attachmentLink.getAttribute('href'),page.url()).href);
  assert.equal(attachmentResponse.status(),200);
  assert.deepEqual(await attachmentResponse.body(),diagnosticBytes);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Скачать PDF',exact:true}).click();
  const download = await downloadPromise;
  assert.equal(await download.failure(),null);
  assert.match(download.suggestedFilename(),/BMSPORT-.*\.pdf/);
  assert.deepEqual(errors,[]);
  mkdirSync('test-results',{recursive:true});
  await page.screenshot({path:'test-results/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
  console.log('Browser OK: save, reload, Cyrillic form, PDF download, mobile width; no page errors.');
} finally {
  await browser?.close(); await new Promise(resolve => server.close(resolve)); store.close(); rmSync(directory,{recursive:true,force:true});
}

